function applyOverrides (obj, map) {
    if (typeof obj === 'string') return obj;
    if (Array.isArray(obj)) return obj.map(item => applyOverrides(item, map));
    if (obj && typeof obj === 'object') {
        const next = {};
        for (const key of Object.keys(obj)) {
            const value = obj[key];
            if (Object.prototype.hasOwnProperty.call(map, key)) {
                if (value && typeof value === 'object' && value.message) {
                    next[key] = Object.assign({}, value, {message: map[key]});
                } else {
                    next[key] = map[key];
                }
            } else {
                next[key] = applyOverrides(value, map);
            }
        }
        return next;
    }
    return obj;
}

function generateLocale (locale) {
    const map = overrides[locale] || {};
    for (const component of COMPONENTS) {
        const srcPath = path.join(EDITOR_ROOT, component, 'id.json');
        const destPath = path.join(EDITOR_ROOT, component, `${locale}.json`);
        const raw = JSON.parse(fs.readFileSync(srcPath, 'utf8'));
        const translated = applyOverrides(raw, map);
        fs.writeFileSync(destPath, `${JSON.stringify(translated, null, 4)}\n`, 'utf8');
        console.log(`wrote ${path.relative(process.cwd(), destPath)}`);
    }
}

for (const locale of Object.keys(overrides)) {
    generateLocale(locale);
}

